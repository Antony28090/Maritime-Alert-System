    forecasters = {"LSTM": lstm, "ConstVel": ConstantVelocityForecaster(),
                   "Kalman": KalmanForecaster(), "Reactive": ReactiveGeofence()}

    df_all = pd.read_csv("data/vessel_data.csv")
    if "split" in df_all.columns:
        df_test = df_all[df_all["split"] == "test"]
        split_note = "held-out trips (split == 'test' in data/vessel_data.csv)"
    else:
        df_test = df_all
        split_note = ("WARNING: no 'split' column found; scored on all trips "
                      "(in-sample). Re-run python -m src.train_model.")
    print(f"One-step forecast evaluation set: {split_note}; "
          f"{df_test['trip_id'].nunique()} trips, {len(df_test)} fixes")

    print("\n== Zone classifier ==")
    zone_uniform = eval_classifier_on_uniform(zone_model)
    zone_traj = eval_classifier_on_trajectories(zone_model, df_all)
    print(f"  uniform grid acc {zone_uniform['accuracy']:.4f} | trajectories acc {zone_traj['accuracy']:.4f}")

    print("\n== One-step forecast error (held-out) ==")
    one_step = {}
    for name in ROLLOUT:
        one_step[name] = eval_forecaster_trajectory(forecasters[name], df_test)
        lo, hi = one_step[name]["ade_m_ci95"]
        print(f"  {name:<9} ADE {one_step[name]['ade_m_approx']:.1f} m [{lo:.1f}, {hi:.1f}]  "
              f"RMSE {one_step[name]['rmse_m_approx']:.1f} m  (n={one_step[name]['n_samples']})")

    print("\n== Horizon sweep over seeds ==")
    awt_parts, far_parts, gen_info = [], [], {}
    for si, (sf, sn) in enumerate(SEEDS):
        forced, near, info = make_trip_sets(sf, sn)
        gen_info[f"seed{si}"] = {"forced": sf, "near_miss": sn, **info}
        a, f = run_horizon_sweep(forecasters, forced, near, seed_tag=si)
        awt_parts.append(a)
        far_parts.append(f)
    awt_df = pd.concat(awt_parts, ignore_index=True)
    far_df = pd.concat(far_parts, ignore_index=True)
    awt_df.to_csv("results/awt.csv", index=False)
    far_df.to_csv("results/far_sweep.csv", index=False)
    sweep = summarise_sweep(awt_df, far_df)

    print("\n== Latency (machine should be otherwise idle) ==")
    latency = bench_latency(zone_model, lstm)
    fs = latency["full_alerting_step"]
    print(f"  full alerting step: mean {fs['mean_ms']:.1f} ms  median {fs['median_ms']:.1f} ms  "
          f"p99 {fs['p99_ms']:.1f} ms  (n={fs['n']})")

    n_params = int(lstm.model.count_params())
    summary = {
        "config": {
            "n_forced_trips_per_seed": N_FORCED, "n_near_miss_trips_per_seed": N_NEAR,
            "n_seeds": len(SEEDS), "seeds": gen_info,
            "trip_len_forced": TRIP_LEN, "trip_len_near_miss": NEAR_LEN,
            "post_cross_ticks": POST_CROSS_TICKS,
            "horizons": HORIZONS, "predicates": PREDICATES, "policies": POLICIES,
            "approach_bins_km": APPROACH_BINS, "bootstrap_resamples": N_BOOT,
            "default_forecast_horizon": FORECAST_HORIZON, "lstm_lookback": LSTM_LOOKBACK,
            "danger_km": DANGER_DIST_KM, "caution_km": CAUTION_DIST_KM,
            "one_step_eval_set": split_note,
            "one_step_eval_trips": int(df_test["trip_id"].nunique()),
            "wall_clock_s": float(time.perf_counter() - t_start),
        },
        "model": {"lstm_trainable_params": n_params},
        "zone_classifier_uniform": zone_uniform,
        "zone_classifier_trajectories": zone_traj,
        "trajectory_1step_heldout": one_step,
        "horizon_sweep": sweep,
        "latency": latency,
    }
    with open("results/summary.json", "w") as fh:
        json.dump(summary, fh, indent=2)

    print("\n== Sweep summary (pooled over seeds; 95% bootstrap CI) ==")
    r = sweep["reactive"]
    ap = sweep["near_miss_closest_approach"]
    print(f"  near-miss closest approach: mean {ap['d_min_km_mean']:.2f} km, "
          f"range {ap['d_min_km_min']:.2f}-{ap['d_min_km_max']:.2f}, bins {ap['n_by_bin']}")
    print(f"  Reactive (zone rule): AWT mean {r['awt']['awt_mean']:.2f} "
          f"{r['awt']['awt_mean_ci95']}, FAR {r['false_alert']['false_alert_rate']:.2f}")
    for predicate in PREDICATES:
        print(f"  -- predicate: {predicate}")
        for H in HORIZONS:
            for name in POLICIES:
                s = sweep["by_predicate"][predicate][str(H)][name]
                a, fr = s["awt"], s["false_alert"]
                bins = "  ".join(f"{k}:{(v['false_alert_rate'] or 0)*100:3.0f}%" for k, v in fr["by_closest_approach_km"].items())
                print(f"     H={H:>2} {name:<9} AWT {a['awt_mean']:5.2f} [{a['awt_mean_ci95'][0]:.2f},{a['awt_mean_ci95'][1]:.2f}] "
                      f"seed-sd {a['across_seed_std']:.2f}  FAR {fr['false_alert_rate']*100:3.0f}% "
                      f"[{fr['false_alert_rate_ci95'][0]*100:.0f},{fr['false_alert_rate_ci95'][1]*100:.0f}]  "
                      f"eq1 {s['eq1_residual_ticks']:+.2f}  by-approach {bins}")
    print(f"\n  LSTM params: {n_params}   total wall-clock {summary['config']['wall_clock_s']:.0f}s")
    print("Wrote results/summary.json, results/awt.csv, results/far_sweep.csv")


