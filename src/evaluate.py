N_FORCED = 50            # forced-crossing trips per seed (AWT)
N_NEAR = 50              # near-miss trips per seed (false-alert rate)
TRIP_LEN = 150           # ticks per forced trip
NEAR_LEN = 220           # ticks per near-miss trip (approach + trawl + return to port)
HORIZONS = [5, 10, 15, 20]
H_MAX = max(HORIZONS)
PREDICATES = ["buffer", "crossing"]
POST_CROSS_TICKS = 5     # forced trips are cut this many ticks after crossing
SEEDS = [(20260811, 20260812), (20260901, 20260902), (20260903, 20260904)]
APPROACH_BINS = [(0.0, 2.5), (2.5, 3.5), (3.5, 99.0)]   # closest approach, km
