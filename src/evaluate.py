"""
End-to-end evaluation of the alerting pipeline.

Experiments (all regenerated by `python -m src.evaluate`):

  1. Zone classifier  - accuracy / per-class P-R-F1 on (a) a held-out uniform
                        sample of the region and (b) the synthetic trajectory set.
  2. One-step forecast - MAE / RMSE / ADE for LSTM, ConstVel, Kalman, scored
                        ONLY on trips with split == 'test' in data/vessel_data.csv.
  3. Horizon sweep    - for H in HORIZONS, each alerting policy, each alert
                        predicate, and each of SEEDS independent trip sets:
                          * Advance Warning Time on N_FORCED forced-crossing trips
                          * False-alert rate on N_NEAR near-miss trips that never
                            enter the DANGER zone (so any Danger alert is false)
                        Policies:
                          LSTM / ConstVel / Kalman - recursive rollout of a
                                     one-step forecaster, H steps
                          Analytic - zero-parameter time-to-line: smoothed
                                     velocity over the last L deltas, closing
                                     speed against the nearest segment's normal,
                                     fire when the straight-line time to the
                                     line (or buffer edge) is <= H.  No rollout.
                          Reactive - fires on the DANGER zone rule (H-independent)
                        Predicates:
                          'buffer'   - fire if a projected fix is on the SL side
                                       OR inside the 2 km DANGER buffer (shipped)
                          'crossing' - fire only on a projected SL-side fix
                        Reports pooled statistics over all seeds with 1,000-
                        resample bootstrap 95% CIs, the per-seed means, eq. (1)
                        residuals, and false-alert rate binned by each trip's
                        closest approach to the line.
  4. Latency          - per-tick wall-clock for the full single-vessel alerting
                        step (zone predict + 1-step + H-step rollout + predicate),
                        using the same un-batched call path as app.py.
  5. Model size       - trainable parameter count of the LSTM.

Outputs:
    results/awt.csv         one row per (seed, policy, predicate, H, forced trip)
    results/far_sweep.csv   one row per (seed, policy, predicate, H, near-miss trip)
    results/summary.json    everything the paper cites
"""

