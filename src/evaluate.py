"""
End-to-end evaluation of the alerting pipeline.

Experiments (all regenerated by `python -m src.evaluate`):

  1. Zone classifier  - accuracy / per-class P-R-F1 on (a) a held-out uniform
                        sample of the region and (b) the synthetic trajectory set.
  2. One-step forecast - MAE / RMSE / ADE for LSTM, ConstVel, Kalman, scored
                        ONLY on trips with split == 'test' in data/vessel_data.csv.
  3. Horizon sweep    - for H in HORIZONS, each predictive policy, and each alert
                        predicate:
                          * Advance Warning Time on N_FORCED forced-crossing trips
                          * False-alert rate on N_NEAR near-miss trips that never
                            enter the DANGER zone (so any Danger alert is false)
                        Predicates:
                          'buffer'   - fire if any projected fix is on the SL side
                                       OR inside the 2 km DANGER buffer (what the
                                       dashboard ships)
                          'crossing' - fire only if a projected fix is on the SL
                                       side (a predicted crossing)
                        The reactive geofence is H-independent and is scored once.
                        Also checks eq. (1): AWT(pi_H) ~= H + AWT(reactive) for the
                        buffer predicate, and AWT ~= H for the crossing predicate.
  4. Latency          - per-tick wall-clock for the full single-vessel alerting
                        step (zone predict + 1-step + H-step rollout + predicate),
                        using the same un-batched call path as app.py.
  5. Model size       - trainable parameter count of the LSTM.

Trip sets are generated once with fixed seeds and shared across every policy,
horizon and predicate, so comparisons are paired.  One rollout of max(HORIZONS)
steps per tick serves every shorter horizon (a recursive rollout's first H steps
are identical regardless of the total length) and both predicates; LSTM
rollouts are batched across trips.

Outputs:
    results/awt.csv         one row per (policy, predicate, H, forced trip)
    results/far_sweep.csv   one row per (policy, predicate, H, near-miss trip)
    results/summary.json    everything the paper cites
"""

